CREATE OR REPLACE FUNCTION "public"."validar_donacion_alimento_canonico"()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF NEW.alimento_id IS NULL THEN
    RAISE EXCEPTION 'Las nuevas donaciones deben referenciar un alimento existente';
  END IF;

  IF COALESCE(NEW.es_producto_personalizado, false) THEN
    RAISE EXCEPTION 'Las nuevas donaciones no pueden usar producto personalizado';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS "trigger_validar_donacion_alimento_canonico"
  ON "public"."donaciones";

CREATE TRIGGER "trigger_validar_donacion_alimento_canonico"
  BEFORE INSERT ON "public"."donaciones"
  FOR EACH ROW
  EXECUTE FUNCTION "public"."validar_donacion_alimento_canonico"();
