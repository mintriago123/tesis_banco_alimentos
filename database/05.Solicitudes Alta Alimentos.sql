-- Flujo separado para solicitar alta de alimentos canonicos del catalogo.

CREATE TABLE IF NOT EXISTS "public"."solicitudes_alta_alimentos" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "solicitante_id" uuid NOT NULL REFERENCES "public"."usuarios"("id"),
  "nombre" text NOT NULL,
  "categoria" text NOT NULL,
  "comentario_donante" text NULL,
  "estado" text NOT NULL DEFAULT 'pendiente',
  "comentario_admin" text NULL,
  "alimento_creado_id" bigint NULL REFERENCES "public"."alimentos"("id"),
  "revisado_por" uuid NULL REFERENCES "public"."usuarios"("id"),
  "fecha_revision" timestamptz NULL,
  "created_at" timestamptz DEFAULT now(),
  "updated_at" timestamptz DEFAULT now(),
  CONSTRAINT "solicitudes_alta_alimentos_estado_check"
    CHECK ("estado" = ANY (ARRAY['pendiente'::text, 'aprobada'::text, 'rechazada'::text])),
  CONSTRAINT "solicitudes_alta_alimentos_nombre_check"
    CHECK (length(trim("nombre")) > 0),
  CONSTRAINT "solicitudes_alta_alimentos_categoria_check"
    CHECK (length(trim("categoria")) > 0)
);

CREATE TABLE IF NOT EXISTS "public"."solicitudes_alta_alimentos_unidades" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "solicitud_id" uuid NOT NULL REFERENCES "public"."solicitudes_alta_alimentos"("id") ON DELETE CASCADE,
  "unidad_id" bigint NOT NULL REFERENCES "public"."unidades"("id"),
  "es_unidad_principal" boolean DEFAULT false,
  CONSTRAINT "solicitudes_alta_alimentos_unidades_unique" UNIQUE ("solicitud_id", "unidad_id")
);

CREATE INDEX IF NOT EXISTS "idx_solicitudes_alta_alimentos_solicitante"
  ON "public"."solicitudes_alta_alimentos" ("solicitante_id");

CREATE INDEX IF NOT EXISTS "idx_solicitudes_alta_alimentos_estado"
  ON "public"."solicitudes_alta_alimentos" ("estado", "created_at" DESC);

CREATE INDEX IF NOT EXISTS "idx_solicitudes_alta_alimentos_unidades_solicitud"
  ON "public"."solicitudes_alta_alimentos_unidades" ("solicitud_id");

DROP TRIGGER IF EXISTS "trigger_solicitudes_alta_alimentos_updated_at"
